def get_icon(name: str, color: str = "#d4d4d8", size: int = 18) -> QIcon:
    """Returns a high-DPI QIcon from monochrome SVG definition."""
    svg_template = SVG_DEFS.get(name)
    if not svg_template:
        return QIcon()

    svg_content = svg_template.format(color=color).strip()
    renderer = QSvgRenderer(QByteArray(svg_content.encode("utf-8")))

    pixmap = QPixmap(size, size)
    pixmap.fill(QColor(0, 0, 0, 0))

    painter = QPainter(pixmap)
    renderer.render(painter)
    painter.end()

    return QIcon(pixmap)

def get_pixmap(name: str, color: str = "#d4d4d8", size: int = 24) -> QPixmap:
    """Returns a rendered QPixmap."""
    svg_template = SVG_DEFS.get(name)
    if not svg_template:
        pix = QPixmap(size, size)
        pix.fill(QColor(0, 0, 0, 0))
        return pix

    svg_content = svg_template.format(color=color).strip()
    renderer = QSvgRenderer(QByteArray(svg_content.encode("utf-8")))

    pixmap = QPixmap(size, size)
    pixmap.fill(QColor(0, 0, 0, 0))

    painter = QPainter(pixmap)
    renderer.render(painter)
    painter.end()

    return pixmap
